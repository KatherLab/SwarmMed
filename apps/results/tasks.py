"""
Celery background tasks for the results application.
Handles synchronization of results from S3 and the execution of user-submitted
visualization scripts in an isolated environment.
"""

import ast
import os
import tempfile
import traceback

import boto3
from celery import shared_task
from django.conf import settings
from django.utils import timezone

from apps.logs import logger
from apps.logs.context import set_context
from apps.project.models import Project
from apps.training.models import TrainingJob
from apps.data.utils import get_s3_client

from .models import (
    ResultsVisualizationPlot,
    ResultsVisualizationRun,
    TrainingResult,
)
from .visualization import ResultsVisualizationContext


@shared_task
def sync_project_results(project_uuid):
    """
    Scans the S3 results folder for a project and updates our database.
    Ensures that files generated by training are visible in the UI.
    """
    # Import inside to avoid circular dependencies.
    from apps.training.tasks import monitor_training_jobs

    log = logger.get_logger()
    try:
        # Step 1: Trigger training job monitoring to ensure local results are
        # uploaded.
        log.results.info(
            f"Running monitor_training_jobs before sync for {project_uuid}")
        monitor_training_jobs()

        project = Project.objects.get(identifier=project_uuid)
        log.results.info(f"Starting results sync for project {project_uuid}")

        s3 = get_s3_client()
        prefix = f"{project.identifier}/results/"
        paginator = s3.get_paginator('list_objects_v2')

        # Step 2: Iterate through all objects in the project's results prefix
        # in S3.
        for page in paginator.paginate(
                Bucket=settings.AWS_STORAGE_BUCKET_NAME,
                Prefix=prefix):
            for obj in page.get('Contents', []):
                key = obj['Key']
                if key.endswith('/'):
                    continue

                # Filter out irrelevant files (system files, source code).
                filename = os.path.basename(key)
                if (filename.startswith('.') or
                        filename.endswith('.py') or
                        filename.endswith('.pyc')):
                    continue

                # S3 Key structure:
                # <project_uuid>/results/<job_id>/<client>/<file>
                parts = key.split('/')
                if len(parts) < 4:
                    log.results.warning(f"Skipping malformed S3 key: {key}")
                    continue

                job_id_from_s3_key = parts[2]
                last_modified = obj.get('LastModified')

                job = None
                try:
                    # Attempt to find the matching TrainingJob record.
                    # We use 'icontains' because flare_job_id might be a
                    # complex string.
                    job_obj = TrainingJob.objects.filter(
                        project=project,
                        flare_job_id__icontains=job_id_from_s3_key
                    ).first()

                    if job_obj:
                        job = job_obj
                    else:
                        # Fallback for complex job ID storage (e.g.,
                        # stringified JSON logs).
                        all_jobs = TrainingJob.objects.filter(project=project)
                        for potential_job in all_jobs:
                            raw_flare_job_id = potential_job.flare_job_id or ""
                            actual_job_id = None
                            try:
                                # Try parsing the field if it looks like a
                                # list/dict.
                                parsed = ast.literal_eval(raw_flare_job_id)
                                if isinstance(parsed, list):
                                    for item in parsed:
                                        if (isinstance(item, dict) and
                                                item.get('type') == 'string' and
                                                'Submitted job:' in item.get('data', '')):
                                            actual_job_id = item.get(
                                                'data', '').split(':')[-1].strip()
                                            break
                            except (ValueError, SyntaxError):
                                pass

                            if not actual_job_id:
                                actual_job_id = raw_flare_job_id

                            if (actual_job_id and actual_job_id.strip()
                                    == job_id_from_s3_key):
                                job = potential_job
                                break

                except TrainingJob.DoesNotExist:
                    log.results.warning(
                        f"TrainingJob not found for: {job_id_from_s3_key}")
                    job = None

                if job:
                    # Step 3: Create or update the TrainingResult record.
                    tr, created = TrainingResult.objects.get_or_create(
                        job=job,
                        file_path=key,
                        defaults={
                            'file_size': obj.get('Size', 0),
                            'created_at': last_modified
                        }
                    )
                    if not created:
                        # Update metadata if the file changed.
                        if tr.file_size != obj.get('Size', 0):
                            tr.file_size = obj.get('Size', 0)
                            tr.save(update_fields=['file_size'])
                        if tr.created_at != last_modified:
                            tr.created_at = last_modified
                            tr.save(update_fields=['created_at'])
                else:
                    log.results.warning(f"No TrainingJob for S3 result: {key}")

        log.results.info(f"Finished results sync for project {project_uuid}")

    except Project.DoesNotExist:
        log.results.error(f"Project {project_uuid} not found during sync.")
    except Exception as e:
        log.results.error(f"Error during results sync: {e}", exc_info=True)


@shared_task(bind=True)
def run_results_visualization_task(self, run_id, job_id):
    """
    Executes a user-submitted visualization script in a background worker.
    The script is wrapped in a context that provides access to project data.
    """
    try:
        run = ResultsVisualizationRun.objects.get(id=run_id)
        project = run.project
        user = run.user

        # Set up logging context so logs are attributed to the right
        # project/user.
        set_context(user=user, project=project)
        log = logger.get_logger()

        log.results.info(f"Starting results visualization for job {job_id}")

        run.status = 'running'
        run.started_at = timezone.now()
        run.celery_task_id = self.request.id
        run.save()

        # Step 1: Download the user's visualization script from S3.
        script_prefix = f"{project.identifier}/code/results_visualization/"
        script_content = ""

        try:
            s3 = boto3.client(
                's3',
                endpoint_url=settings.AWS_S3_ENDPOINT_URL,
                aws_access_key_id=settings.AWS_ACCESS_KEY_ID,
                aws_secret_access_key=settings.AWS_SECRET_ACCESS_KEY
            )

            response = s3.list_objects_v2(
                Bucket=settings.AWS_STORAGE_BUCKET_NAME,
                Prefix=script_prefix
            )
            contents = response.get('Contents', [])
            py_scripts = [obj['Key']
                          for obj in contents if obj['Key'].endswith('.py')]

            if not py_scripts:
                raise Exception(f"No .py scripts found at {script_prefix}")

            # We take the first Python script in the directory.
            script_key = py_scripts[0]
            log.results.info(f"Downloading script: {script_key}")

            response = s3.get_object(
                Bucket=settings.AWS_STORAGE_BUCKET_NAME,
                Key=script_key
            )
            script_content = response['Body'].read().decode('utf-8')

        except Exception as e:
            log.results.error(f"Error downloading script: {str(e)}")
            raise

        # Step 2: Prepare the execution environment.
        # We inject a 'visualization' object into the script's global scope.
        with ResultsVisualizationContext(str(project.identifier),
                                         job_id,
                                         str(run.id)) as context:

            with tempfile.NamedTemporaryFile(mode='w', suffix='.py',
                                             delete=False) as script_file:
                # Boilerplate to expose the context API to the user's script.
                script_with_context = f"""
# Auto-injected results visualization context
import sys
import os
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import torch
import numpy as np
from apps.data.filesystem import DataFileSystem

class ResultsVisualizationContextWrapper:
    def __init__(self, context):
        self._context = context

    def load_weights(self, model):
        return self._context.load_weights(model)

    def save_plot(self, title="Untitled Plot"):
        self._context.save_plot(title)

    def get_model(self, client_name="fl-client-1", model_filename="model.pt"):
        return self._context.get_model(client_name, model_filename)

    def get_model_path(self, client_name="fl-client-1", model_filename="model.pt"):
        return self._context.get_model_path(client_name, model_filename)

    def open(self, relative_path, mode='r', **kwargs):
        return self._context.open(relative_path, mode, **kwargs)

    def exists(self, relative_path):
        return self._context.exists(relative_path)

    def listdir(self, relative_path=""):
        return self._context.listdir(relative_path)

    def get_data_path(self, relative_path=""):
        return self._context.get_data_path(relative_path)

visualization = ResultsVisualizationContextWrapper(context)

# User script starts here:
{script_content}
"""
                script_file.write(script_with_context)
                script_file.flush()

                # Step 3: Execute the script and capture its output.
                import io
                from contextlib import redirect_stderr, redirect_stdout

                output_capture = io.StringIO()
                try:
                    with redirect_stdout(output_capture), redirect_stderr(output_capture):
                        exec_globals = {
                            'context': context,
                            '__name__': '__main__',
                            '__file__': script_file.name
                        }
                        # 'exec' runs the Python code in the current process.
                        exec(
                            compile(
                                script_with_context,
                                script_file.name,
                                'exec'),
                            exec_globals)

                    run.success = True
                    script_output = output_capture.getvalue()
                    run.output = (
                        "Visualization completed successfully.\n\n"
                        f"Script Output:\n{script_output}\n\n"
                        f"Generated {len(context.plots)} plots."
                    )

                except Exception as script_error:
                    run.success = False
                    script_output = output_capture.getvalue()
                    run.error_message = str(script_error)
                    run.output = (
                        f"Script Output before failure:\n{script_output}\n\n"
                        f"Error:\n{traceback.format_exc()}"
                    )
                    log.results.error(
                        f"Script execution failed: {str(script_error)}")

                finally:
                    # Clean up the temporary script file.
                    try:
                        os.unlink(script_file.name)
                    except OSError:
                        pass

            # Step 4: Save any generated plots to the database.
            for plot_data in context.plots:
                ResultsVisualizationPlot.objects.create(
                    visualization_run=run,
                    **plot_data
                )

        run.status = 'completed'
        run.completed_at = timezone.now()
        run.save()

        log.results.info("Results visualization task finished.")
        return {
            'success': run.success,
            'plots_count': len(context.plots),
            'output': run.output
        }

    except Exception as e:
        # Global error handler to ensure the run status is updated to 'failed'.
        try:
            run = ResultsVisualizationRun.objects.get(id=run_id)
            run.status = 'failed'
            run.success = False
            run.error_message = str(e)
            run.output = traceback.format_exc()
            run.completed_at = timezone.now()
            run.save()
            log.results.error(
                f"Visualization task failed completely: {str(e)}")
        except Exception:
            pass
        raise e
