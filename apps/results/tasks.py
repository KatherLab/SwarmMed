_UUID_RE = re.compile(
    r"([0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})"
)


def _extract_flare_job_uuid(flare_job_id_raw: str) -> str | None:
    """Best-effort extraction of the NVFlare job UUID from stored flare_job_id."""
    if not flare_job_id_raw:
        return None

    # Case 1: it already contains a UUID.
    m = _UUID_RE.search(str(flare_job_id_raw))
    if m:
        return m.group(1)

    # Case 2: some code stores a stringified list/dict of log records.
    try:
        parsed = ast.literal_eval(flare_job_id_raw)
        if isinstance(parsed, list):
            for item in parsed:
                if isinstance(item, dict):
                    data = item.get("data", "")
                    if isinstance(data, str) and "Submitted job:" in data:
                        m2 = _UUID_RE.search(data)
                        if m2:
                            return m2.group(1)
    except (ValueError, SyntaxError, TypeError):
        return None

    return None


@shared_task
def sync_project_results(project_uuid):
    """
    Scans the S3 results folder for a project and updates our database.
    Ensures that files generated by training are visible in the UI.
    """
    # Import inside to avoid circular dependencies.
    from training.tasks import monitor_training_jobs

    log = logger.get_logger()
    try:
        # Step 1: Trigger training job monitoring to ensure local results are
        # uploaded.
        log.results.info(
            f"Running monitor_training_jobs before sync for {project_uuid}"
        )
        monitor_training_jobs()

        project = Project.objects.get(identifier=project_uuid)
        log.results.info(f"Starting results sync for project {project_uuid}")

        # Pre-compute job UUID -> TrainingJob mapping once.
        job_lookup: dict[str, TrainingJob] = {}
        for job in TrainingJob.objects.filter(project=project).only(
            "id", "flare_job_id", "project"
        ):
            job_uuid = _extract_flare_job_uuid(job.flare_job_id or "")
            if job_uuid:
                job_lookup[job_uuid] = job

        s3 = get_s3_client()
        prefix = f"{project.identifier}/results/"
        paginator = s3.get_paginator("list_objects_v2")

        # Step 2: Iterate through all objects in the project's results prefix
        # in S3.
        for page in paginator.paginate(
            Bucket=settings.AWS_STORAGE_BUCKET_NAME, Prefix=prefix
        ):
            for obj in page.get("Contents", []):
                key = obj["Key"]
                if key.endswith("/"):
                    continue

                # Filter out irrelevant files (system files, source code).
                filename = os.path.basename(key)
                if (
                    filename.startswith(".")
                    or filename.endswith(".py")
                    or filename.endswith(".pyc")
                ):
                    continue

                # S3 Key structure:
                # <project_uuid>/results/<job_id>/<client>/<file>
                parts = key.split("/")
                if len(parts) < 4:
                    log.results.warning(f"Skipping malformed S3 key: {key}")
                    continue

                job_id_from_s3_key = parts[2]
                last_modified = obj.get("LastModified")

                job = job_lookup.get(job_id_from_s3_key)
                if not job:
                    # Backward-compatible fallback (rare): try icontains once.
                    job = (
                        TrainingJob.objects.filter(
                            project=project, flare_job_id__icontains=job_id_from_s3_key
                        )
                        .only("id", "flare_job_id", "project")
                        .first()
                    )

                if job:
                    # Step 3: Create or update the TrainingResult record.
                    tr, created = TrainingResult.objects.get_or_create(
                        job=job,
                        file_path=key,
                        defaults={
                            "file_size": obj.get("Size", 0),
                            "created_at": last_modified,
                        },
                    )
                    if not created:
                        # Update metadata if the file changed.
                        if tr.file_size != obj.get("Size", 0):
                            tr.file_size = obj.get("Size", 0)
                            tr.save(update_fields=["file_size"])
                        if tr.created_at != last_modified:
                            tr.created_at = last_modified
                            tr.save(update_fields=["created_at"])
                else:
                    log.results.warning(f"No TrainingJob for S3 result: {key}")

        log.results.info(f"Finished results sync for project {project_uuid}")

    except Project.DoesNotExist:
        log.results.error(f"Project {project_uuid} not found during sync.")
    except Exception as e:
        log.results.error(f"Error during results sync: {e}", exc_info=True)


@shared_task(bind=True)
def run_results_visualization_task(self, run_id, job_id):
    """
    Background task to execute a user's results visualization script securely.
    """
    try:
        run = ResultsVisualizationRun.objects.get(id=run_id)
        project = run.project
        user = run.user

        set_context(user=user, project=project)
        log = logger.get_logger()

        log.results.info(f"Starting results visualization for job {job_id}")

        run.status = "running"
        run.started_at = timezone.now()
        run.celery_task_id = self.request.id
        # Ensure flare_job_id is preserved if it was passed to the task
        if not run.flare_job_id and job_id:
            run.flare_job_id = job_id
        run.save()

        # Step 1: Download the user's visualization script from S3.
        script_prefix = f"{project.identifier}/code/results_visualization/"
        script_content = ""

        try:
            s3 = boto3.client(
                "s3",
                endpoint_url=settings.AWS_S3_ENDPOINT_URL,
                aws_access_key_id=settings.AWS_ACCESS_KEY_ID,
                aws_secret_access_key=settings.AWS_SECRET_ACCESS_KEY,
            )

            response = s3.list_objects_v2(
                Bucket=settings.AWS_STORAGE_BUCKET_NAME, Prefix=script_prefix
            )
            contents = response.get("Contents", [])
            py_scripts = [obj["Key"] for obj in contents if obj["Key"].endswith(".py")]

            if not py_scripts:
                raise Exception(f"No .py scripts found at {script_prefix}")

            script_key = py_scripts[0]
            log.results.info(f"Downloading script: {script_key}")

            response = s3.get_object(
                Bucket=settings.AWS_STORAGE_BUCKET_NAME, Key=script_key
            )
            script_content = response["Body"].read().decode("utf-8")

        except Exception as e:
            log.results.error(f"Error downloading script: {str(e)}")
            raise

        # Step 2: Prepare the sandbox execution environment.
        with ResultsVisualizationContext(
            str(project.identifier), job_id, str(run.id)
        ) as context:
            # Populate data filesystem so files are visible in sandbox
            context.filesystem.download_all()

            # Also download the model weights to the temp directory so they are available in the sandbox
            try:
                # Use the flare_id passed to the task.
                # If context.job exists, we try to clean it, otherwise use job_id directly.
                flare_id = job_id
                if context.job:
                    flare_id = context.job.flare_job_id
                    try:
                        parsed = ast.literal_eval(flare_id)
                        if isinstance(parsed, list):
                            for item in parsed:
                                if (
                                    isinstance(item, dict)
                                    and item.get("type") == "string"
                                    and "Submitted job:" in item.get("data", "")
                                ):
                                    flare_id = (
                                        item.get("data", "").split(":")[-1].strip()
                                    )
                                    break
                    except (ValueError, SyntaxError, TypeError):
                        pass

                # Check S3 for the most likely model file
                from django.core.files.storage import default_storage
                import shutil

                s3 = get_s3_client()
                results_prefix = f"{project.identifier}/results/{flare_id}/"
                paginator = s3.get_paginator("list_objects_v2")

                found_key = None
                for page in paginator.paginate(
                    Bucket=settings.AWS_STORAGE_BUCKET_NAME, Prefix=results_prefix
                ):
                    for obj in page.get("Contents", []):
                        key = obj["Key"]
                        if key.endswith((".pt", ".npy", ".npz")):
                            found_key = key
                            break
                    if found_key:
                        break

                if found_key:
                    sandbox_model_path = os.path.join(
                        context.filesystem.temp_dir,
                        "model_weights" + os.path.splitext(found_key)[1],
                    )
                    with default_storage.open(found_key, "rb") as s3_file:
                        with open(sandbox_model_path, "wb") as local_file:
                            shutil.copyfileobj(s3_file, local_file)
                    log.results.info(
                        f"Pre-downloaded model weights from S3: {found_key}"
                    )
            except Exception as e:
                log.results.warning(f"Could not pre-download model weights: {e}")

            script_wrapper = f"""
import sys
import os
import json
import base64
import io
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import torch
import numpy as np

class ResultsVisualizationHelper:
    def __init__(self, data_root, plots_dir):
        self.data_root = data_root
        self.plots_dir = plots_dir
        self.plot_count = 0

    def load_weights(self, model):
        # Look for model weights file in data root
        weights_path = None
        for ext in ['.pt', '.npy', '.npz']:
            potential_path = os.path.join(self.data_root, "model_weights" + ext)
            if os.path.exists(potential_path):
                weights_path = potential_path
                break

        if not weights_path:
            # Fallback: look for ANY model-like file
            import glob
            for ext in ['*.pt', '*.npy', '*.npz']:
                files = glob.glob(os.path.join(self.data_root, ext))
                if files:
                    weights_path = files[0]
                    break

        if not weights_path:
            print("No model weights file found in sandbox data directory.")
            return False

        try:
            if weights_path.endswith('.pt'):
                weights = torch.load(weights_path, map_location='cpu', weights_only=True)
                if hasattr(model, "load_state_dict"):
                    if isinstance(weights, dict):
                        if 'weights' in weights: weights = weights['weights']
                        elif 'model' in weights: weights = weights['model']

                    # Basic DXO unwrapping
                    if isinstance(weights, dict) and 'numpy_key' in weights:
                        weights = weights['numpy_key']

                    # Ensure tensors
                    state_dict = {{k: torch.as_tensor(v) for k, v in weights.items()}}
                    model.load_state_dict(state_dict, strict=False)
                    print(f"Successfully loaded PyTorch weights from {{weights_path}}")
                    return True
            elif weights_path.endswith('.npy') or weights_path.endswith('.npz'):
                # Basic support for numpy weights
                data = np.load(weights_path, allow_pickle=False)
                if weights_path.endswith('.npz'):
                    weights = data.get('params', data.get('weights', data))
                else:
                    weights = data

                if hasattr(model, "set_weights"):
                    # Keras/TF
                    if isinstance(weights, dict):
                        try:
                            sorted_keys = sorted(weights.keys(), key=lambda x: int(x))
                            weights = [np.array(weights[k]) for k in sorted_keys]
                        except Exception:
                            weights = [np.array(v) for k, v in sorted(weights.items())]
                    model.set_weights(weights)
                    print(f"Successfully loaded Keras/TF weights from {{weights_path}}")
                    return True
                elif hasattr(model, "coef_"):
                    # Sklearn
                    if isinstance(weights, dict):
                        for k, v in weights.items():
                            if k in ['coef_', 'intercept_', 'coef', 'intercept']:
                                setattr(model, k, np.array(v))
                    print(f"Successfully loaded Sklearn weights from {{weights_path}}")
                    return True
        except Exception as e:
            print(f"Error loading weights in sandbox: {{e}}")

        return False

    def save_plot(self, title="Untitled Plot"):
        if self.plot_count >= 4:
            return
        self.plot_count += 1

        png_buf = io.BytesIO()
        plt.savefig(png_buf, format='png', dpi=100, bbox_inches='tight', transparent=True)
        png_data = base64.b64encode(png_buf.getvalue()).decode('utf-8')

        svg_buf = io.BytesIO()
        plt.savefig(svg_buf, format='svg', bbox_inches='tight', transparent=True)
        svg_data = base64.b64encode(svg_buf.getvalue()).decode('utf-8')

        plot_data = {{
            'title': title,
            'plot_number': self.plot_count,
            'image_data': png_data,
            'svg_data': svg_data
        }}

        with open(os.path.join(self.plots_dir, f'plot_{{self.plot_count}}.json'), 'w') as f:
            json.dump(plot_data, f)

        plt.clf()

    def get_model(self, client_name="fl-client-1", model_filename="model.pt"):
        # Not fully implemented but won't crash
        return {{}}

    def get_data_path(self, relative_path=""):
        return os.path.join(self.data_root, relative_path)

    def open(self, relative_path, mode='r', **kwargs):
        return open(self.get_data_path(relative_path), mode, **kwargs)

    def exists(self, relative_path):
        return os.path.exists(self.get_data_path(relative_path))

    def listdir(self, relative_path=""):
        return os.listdir(self.get_data_path(relative_path))

visualization = ResultsVisualizationHelper('/home/sandboxuser/data', 'plots')

# --- User script ---
{script_content}
"""

            # Run in sandbox
            result = run_script_in_sandbox(
                script_wrapper,
                context.filesystem.temp_dir,
                str(project.identifier),
                run_type="results_visualization",
            )

            run.success = result["success"]
            run.output = result["output"]

            if not result["success"] and "error" in result:
                run.error_message = result["error"]

            # Step 4: Save any generated plots to the database.
            for plot_data in result.get("plots", []):
                # Handle Base64 conversion to files
                plot_obj = ResultsVisualizationPlot(
                    visualization_run=run,
                    title=plot_data["title"],
                    plot_number=plot_data["plot_number"],
                )

                if plot_data.get("image_data"):
                    img_name = f"plot_{plot_data['plot_number']}.png"
                    img_content = ContentFile(
                        base64.b64decode(plot_data["image_data"]), name=img_name
                    )
                    plot_obj.image_data.save(img_name, img_content, save=False)

                if plot_data.get("svg_data"):
                    svg_name = f"plot_{plot_data['plot_number']}.svg"
                    svg_content = ContentFile(
                        base64.b64decode(plot_data["svg_data"]), name=svg_name
                    )
                    plot_obj.svg_data.save(svg_name, svg_content, save=False)

                plot_obj.save()

        run.status = "completed"
        run.completed_at = timezone.now()
        run.save()

        log.results.info("Results visualization task finished.")
        return {
            "success": run.success,
            "plots_count": len(result.get("plots", [])),
            "output": run.output,
        }

    except Exception as e:
        try:
            run = ResultsVisualizationRun.objects.get(id=run_id)
            run.status = "failed"
            run.success = False
            run.error_message = str(e)
            run.output = traceback.format_exc()
            run.completed_at = timezone.now()
            run.save()
        except Exception as inner_e:
            log.results.critical(
                f"Critical failure in run_results_visualization_task error handler: {inner_e}"
            )
        raise e
