"""Database models for the results application.

Defines structures for storing training results (files), tracking visualization runs,
and storing the resulting plots generated by visualization scripts.
"""

import os

from django.contrib.auth.models import User
from django.db import models

from common.fields import EncryptedTextField
from common.models import AbstractBaseModel
from project.models import Project
from training.models import TrainingJob


def results_visualization_plot_path(instance, filename):
    """Generates a unique path for storing results visualization plots.

    Path: <project_id>/plots/results/<run_id>/<filename>

    Args:
        instance (ResultsVisualizationPlot): The plot instance.
        filename (str): The original filename.

    Returns:
        str: The generated storage path.
    """
    project_id = str(instance.visualization_run.project.identifier)
    run_id = str(instance.visualization_run.id)
    return os.path.join(project_id, "plots", "results", run_id, filename)


class TrainingResult(AbstractBaseModel):
    """Represents a single result file generated by a training job.

    Synced from S3 storage. This could be model weights, log files, etc.

    Attributes:
        job (ForeignKey): Link to the training job that produced this result.
        file_path (CharField): The full path to the file in storage (e.g., S3 key).
        file_size (BigIntegerField): Size of the file in bytes.
    """

    # Link to the training job that produced this result.
    job = models.ForeignKey(
        TrainingJob, on_delete=models.CASCADE, related_name="results"
    )

    # The full path to the file in the storage backend (e.g., S3 key).
    file_path = models.CharField(max_length=1024)

    # Size of the file in bytes.
    file_size = models.BigIntegerField(default=0)

    def __str__(self):
        """String representation of the training result.

        Returns:
            str: Identifier and job reference.
        """
        return f"Result {self.identifier} for job {self.job.identifier}"


class ResultsVisualizationRun(AbstractBaseModel):
    """Tracks the execution of a results visualization script.

    Stores metadata about the run, its status, and logs.

    Attributes:
        project (ForeignKey): The project this visualization belongs to.
        job (ForeignKey): The specific training job being visualized (optional).
        flare_job_id (CharField): The clean NVFlare job ID string.
        user (ForeignKey): The user who triggered the visualization.
        status (CharField): Current execution status.
        started_at (DateTimeField): When the run started.
        completed_at (DateTimeField): When the run finished.
        success (BooleanField): Whether the run was successful.
        output (TextField): Standard output/logs from the script.
        error_message (TextField): Error details if the script failed.
        celery_task_id (CharField): The unique ID of the Celery task.
    """

    # Possible states for a visualization run.
    STATUS_CHOICES = [
        ("pending", "Pending"),  # Task is queued but not yet started.
        ("running", "Running"),  # Task is currently being executed.
        ("completed", "Completed"),  # Task finished successfully.
        ("failed", "Failed"),  # Task encountered an error.
        ("cancelled", "Cancelled"),  # Task was manually stopped by the user.
    ]

    # The project this visualization belongs to.
    project = models.ForeignKey(
        Project,
        on_delete=models.CASCADE,
        related_name="results_visualization_runs",
    )

    # The specific training job being visualized (optional, can visualize
    # project-wide data).
    job = models.ForeignKey(
        TrainingJob,
        on_delete=models.CASCADE,
        related_name="results_visualization_runs",
        null=True,
        blank=True,
    )

    # Stores the clean NVFlare job ID string.
    # Essential for S3-only results that don't have a TrainingJob record.
    flare_job_id = models.CharField(max_length=255, blank=True, db_index=True)

    # The user who triggered the visualization.
    user = models.ForeignKey(User, on_delete=models.CASCADE)

    # Current execution status.
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default="pending")

    # Timing metadata.
    started_at = models.DateTimeField(null=True, blank=True)
    completed_at = models.DateTimeField(null=True, blank=True)

    # Outcome flags and logs.
    success = models.BooleanField(null=True, blank=True)
    # Standard output/logs from the script.
    output = models.TextField(blank=True)
    # Error details if the script failed.
    error_message = models.TextField(blank=True)

    # The unique ID of the Celery task running this visualization.
    # Used to monitor or cancel the background process.
    celery_task_id = models.CharField(max_length=255, blank=True)

    class Meta:
        """Default ordering: newest runs first."""

        ordering = ["-created_at"]


class ResultsVisualizationPlot(AbstractBaseModel):
    """Stores an image (plot) generated by a results visualization script.

    Attributes:
        visualization_run (ForeignKey): Link back to the run that generated this plot.
        title (CharField): Human-readable title for the plot.
        plot_number (IntegerField): The generation order sequence number.
        image_data (ImageField): The image file stored in S3/Filesystem.
        svg_data (FileField): SVG representation of the plot.
    """

    # Link back to the run that generated this plot.
    visualization_run = models.ForeignKey(
        ResultsVisualizationRun, on_delete=models.CASCADE, related_name="plots"
    )

    # Human-readable title for the plot.
    title = models.CharField(max_length=255)

    # The order in which the plot was generated (e.g., 1, 2, 3, 4).
    plot_number = models.IntegerField()

    # The image file stored in S3/Filesystem
    image_data = models.ImageField(
        upload_to=results_visualization_plot_path, max_length=512
    )

    # SVG representation of the plot
    svg_data = models.FileField(
        upload_to=results_visualization_plot_path,
        max_length=512,
        blank=True,
        null=True,
    )

    class Meta:
        """Order plots by their sequence number and ensure uniqueness per run."""

        ordering = ["plot_number"]
        unique_together = ["visualization_run", "plot_number"]


# --------------------------------------------------------------------------
# Explainability: per-case explanations written by a project's
# explainability.py in the sandbox, or imported from a bundle.
# --------------------------------------------------------------------------

EXPLANATION_OUTCOME_CHOICES = [
    ("TP", "True positive"),
    ("FP", "False positive"),
    ("FN", "False negative"),
    ("TN", "True negative"),
    ("correct", "Correct"),
    ("incorrect", "Incorrect"),
]

# Panels with one of these methods show the model's input, not an attribution
# map; they stay visible in blinded review mode.
EXPLANATION_INPUT_METHODS = frozenset({"raw", "input"})


def explanation_image_path(instance, filename):
    """Return the storage path of an explanation image.

    Path: <project_id>/plots/explanations/<run_id>/<filename>. The file name is
    generated by the server (case_NN_panel_K.png or summary_K.png).

    Args:
        instance (ExplanationPanel | ExplanationSummary): The image's record.
        filename (str): The server-generated file name.

    Returns:
        str: The generated storage path.
    """
    run = instance.explanation_run
    return os.path.join(
        str(run.project.identifier),
        "plots",
        "explanations",
        str(run.identifier),
        os.path.basename(filename),
    )


class ExplanationRun(AbstractBaseModel):
    """One set of per-case explanations for a training job.

    Created when a user starts the project's explainability script in the
    sandbox (source "sandbox") or imports a bundle (source "import").

    Attributes:
        project (ForeignKey): The project the explanations belong to.
        job (ForeignKey): The training job explained, if it has a record.
        flare_job_id (CharField): The FLARE job UUID of the explained model.
        user (ForeignKey): The user who started or imported the run.
        source (CharField): "sandbox" or "import".
        status (CharField): Execution status, as for visualization runs.
        success (BooleanField): Whether explanations were stored.
        output (TextField): The end of the script's output (at most 64 KiB).
        error_message (TextField): Why the run stored nothing, if it failed.
        info (JSONField): Methods, target, notes and metrics from the bundle.
        script_sha256 (CharField): SHA-256 of the script that was run.
    """

    STATUS_CHOICES = [
        ("pending", "Pending"),
        ("running", "Running"),
        ("completed", "Completed"),
        ("failed", "Failed"),
        ("cancelled", "Cancelled"),
    ]
    SOURCE_CHOICES = [
        ("sandbox", "Sandbox"),
        ("import", "Import"),
    ]

    project = models.ForeignKey(
        Project, on_delete=models.CASCADE, related_name="explanation_runs"
    )
    job = models.ForeignKey(
        TrainingJob,
        on_delete=models.CASCADE,
        related_name="explanation_runs",
        null=True,
        blank=True,
    )
    flare_job_id = models.CharField(max_length=255, blank=True, db_index=True)
    user = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        related_name="explanation_runs",
        null=True,
        blank=True,
    )
    source = models.CharField(max_length=16, choices=SOURCE_CHOICES, default="sandbox")
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default="pending")
    started_at = models.DateTimeField(null=True, blank=True)
    completed_at = models.DateTimeField(null=True, blank=True)
    success = models.BooleanField(null=True, blank=True)
    output = models.TextField(blank=True)
    error_message = models.TextField(blank=True)
    celery_task_id = models.CharField(max_length=255, blank=True)
    info = models.JSONField(default=dict, blank=True)
    script_sha256 = models.CharField(max_length=64, blank=True)

    class Meta:
        """Default ordering: newest runs first."""

        ordering = ["-created_at"]

    def __str__(self):
        """Return a label without case data."""
        return f"Explanation run {self.identifier}"


class ExplanationCase(AbstractBaseModel):
    """One explained case (the site's pseudonymous case ID and model output)."""

    run = models.ForeignKey(
        ExplanationRun, on_delete=models.CASCADE, related_name="cases"
    )
    position = models.PositiveSmallIntegerField()
    case_id = models.CharField(max_length=128)
    label = models.CharField(max_length=64, blank=True)
    prediction = models.CharField(max_length=64, blank=True)
    target = models.CharField(max_length=64, blank=True)
    score = models.FloatField(null=True, blank=True)
    outcome = models.CharField(
        max_length=16, choices=EXPLANATION_OUTCOME_CHOICES, blank=True
    )
    details = models.JSONField(default=dict, blank=True)

    class Meta:
        """Cases are stored in a random order (see persist_explanation_bundle).

        Positions and case IDs are unique per run.
        """

        ordering = ["position"]
        constraints = [
            models.UniqueConstraint(
                fields=["run", "position"], name="explanation_case_unique_position"
            ),
            models.UniqueConstraint(
                fields=["run", "case_id"], name="explanation_case_unique_case_id"
            ),
        ]

    def __str__(self):
        """Return a label without the case ID (audit entries use it)."""
        return f"Explanation case {self.identifier}"


class ExplanationPanel(AbstractBaseModel):
    """One image of a case: an attribution map or the model's input."""

    case = models.ForeignKey(
        ExplanationCase, on_delete=models.CASCADE, related_name="panels"
    )
    position = models.PositiveSmallIntegerField()
    method = models.CharField(max_length=64)
    title = models.CharField(max_length=255, blank=True)
    image = models.ImageField(upload_to=explanation_image_path, max_length=512)
    width = models.PositiveIntegerField(default=0)
    height = models.PositiveIntegerField(default=0)

    class Meta:
        """Panels keep the bundle's order within a case."""

        ordering = ["position"]
        constraints = [
            models.UniqueConstraint(
                fields=["case", "position"], name="explanation_panel_unique_position"
            ),
        ]

    @property
    def explanation_run(self):
        """Return the run the panel belongs to."""
        return self.case.run

    @property
    def is_input(self):
        """Whether the panel shows the model's input rather than a map."""
        return self.method.strip().lower() in EXPLANATION_INPUT_METHODS

    def __str__(self):
        """Return a label without case data."""
        return f"Explanation panel {self.identifier}"


class ExplanationSummary(AbstractBaseModel):
    """One run-level figure (for example permutation importance)."""

    run = models.ForeignKey(
        ExplanationRun, on_delete=models.CASCADE, related_name="summaries"
    )
    position = models.PositiveSmallIntegerField()
    title = models.CharField(max_length=255, blank=True)
    image = models.ImageField(upload_to=explanation_image_path, max_length=512)
    width = models.PositiveIntegerField(default=0)
    height = models.PositiveIntegerField(default=0)

    class Meta:
        """Summaries keep the bundle's order within a run."""

        ordering = ["position"]
        constraints = [
            models.UniqueConstraint(
                fields=["run", "position"], name="explanation_summary_unique_position"
            ),
        ]

    @property
    def explanation_run(self):
        """Return the run the figure belongs to."""
        return self.run

    def __str__(self):
        """Return a label without case data."""
        return f"Explanation summary {self.identifier}"


class ExplanationReview(AbstractBaseModel):
    """One reviewer's read of a case; rows are never changed (append-only).

    Attributes:
        case (ForeignKey): The reviewed case.
        reviewer (ForeignKey): The user who wrote the review.
        verdict (CharField): "agree", "disagree" or "unsure".
        note (EncryptedTextField): Free text, at most 2,000 characters.
        blinded (BooleanField): Recorded before the reviewer had seen the
            model's output for the case (set by the server).
    """

    VERDICT_CHOICES = [
        ("agree", "Agree"),
        ("disagree", "Disagree"),
        ("unsure", "Unsure"),
    ]

    case = models.ForeignKey(
        ExplanationCase, on_delete=models.CASCADE, related_name="reviews"
    )
    reviewer = models.ForeignKey(
        User, on_delete=models.CASCADE, related_name="explanation_reviews"
    )
    verdict = models.CharField(max_length=16, choices=VERDICT_CHOICES)
    note = EncryptedTextField(blank=True)
    blinded = models.BooleanField(default=False)

    class Meta:
        """Newest reviews first."""

        ordering = ["-created_at", "-id"]

    def __str__(self):
        """Return a label without the note (audit entries use it)."""
        return f"Explanation review {self.identifier}"


class ExplanationReader(AbstractBaseModel):
    """A reviewer's view mode for one run.

    Attributes:
        run (ForeignKey): The run.
        user (ForeignKey): The reviewer.
        blinded (BooleanField): Hide model output until the reviewer saves a
            read of the case. A new row starts in the mode the reviewer last
            chose in the project, and blinded for a reviewer's first run.
        output_seen_at (DateTimeField): When the run's model output was first
            given to this user (blinded mode off, download, CLI listing or
            export, a map or summary served while not blinded). From then on
            every case of the run is shown and reads are not blinded.
    """

    run = models.ForeignKey(
        ExplanationRun, on_delete=models.CASCADE, related_name="readers"
    )
    user = models.ForeignKey(
        User, on_delete=models.CASCADE, related_name="explanation_readers"
    )
    blinded = models.BooleanField(default=False)
    output_seen_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        """One row per run and reviewer."""

        constraints = [
            models.UniqueConstraint(
                fields=["run", "user"], name="explanation_reader_unique_user"
            ),
        ]

    def __str__(self):
        """Return a label without user data."""
        return f"Explanation reader {self.identifier}"
