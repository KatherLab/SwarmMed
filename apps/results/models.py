"""
Database models for the results application.
Defines structures for storing training results (files), tracking visualization runs,
and storing the resulting plots generated by visualization scripts.
"""

import os
import uuid

from django.contrib.auth.models import User
from django.db import models

from apps.project.models import Project
from apps.training.models import TrainingJob


def results_visualization_plot_path(instance, filename):
    """
    Generates a unique path for storing results visualization plots.
    Path: <project_id>/plots/results/<run_id>/<filename>
    """
    project_id = str(instance.visualization_run.project.identifier)
    run_id = str(instance.visualization_run.id)
    return os.path.join(project_id, 'plots', 'results', run_id, filename)


class TrainingResult(models.Model):
    """
    Represents a single result file generated by a training job and synced from S3.
    This could be a model weight file, a log file, or any other output.
    """

    # Link to the training job that produced this result.
    job = models.ForeignKey(
        TrainingJob,
        on_delete=models.CASCADE,
        related_name='results'
    )

    # A unique identifier for this specific result entry.
    identifier = models.UUIDField(
        default=uuid.uuid4,
        editable=False,
        unique=True
    )

    # The full path to the file in the storage backend (e.g., S3 key).
    file_path = models.CharField(max_length=1024)

    # Size of the file in bytes.
    file_size = models.BigIntegerField(default=0)

    # Timestamp when this result record was created in our database.
    created_at = models.DateTimeField(auto_now_add=True, db_index=True)

    def __str__(self):
        """String representation of the training result."""
        return f"Result {self.identifier} for job {self.job.identifier}"


class ResultsVisualizationRun(models.Model):
    """
    Tracks the execution of a results visualization script for a specific project/job.
    Stores metadata about the run, its status, and any output or errors.
    """

    # Possible states for a visualization run.
    STATUS_CHOICES = [
        ('pending', 'Pending'),      # Task is queued but not yet started.
        ('running', 'Running'),      # Task is currently being executed.
        ('completed', 'Completed'),  # Task finished successfully.
        ('failed', 'Failed'),        # Task encountered an error.
        ('cancelled', 'Cancelled'),  # Task was manually stopped by the user.
    ]

    # Primary key using UUID for security and uniqueness across distributed
    # systems.
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False
    )

    # The project this visualization belongs to.
    project = models.ForeignKey(
        Project,
        on_delete=models.CASCADE,
        related_name='results_visualization_runs'
    )

    # The specific training job being visualized (optional, can visualize
    # project-wide data).
    job = models.ForeignKey(
        TrainingJob,
        on_delete=models.CASCADE,
        related_name='results_visualization_runs',
        null=True,
        blank=True
    )

    # Stores the clean NVFlare job ID string. 
    # Essential for S3-only results that don't have a TrainingJob record.
    flare_job_id = models.CharField(max_length=255, blank=True, db_index=True)

    # The user who triggered the visualization.
    user = models.ForeignKey(User, on_delete=models.CASCADE)

    # Current execution status.
    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default='pending'
    )

    # Timing metadata.
    created_at = models.DateTimeField(auto_now_add=True)
    started_at = models.DateTimeField(null=True, blank=True)
    completed_at = models.DateTimeField(null=True, blank=True)

    # Outcome flags and logs.
    success = models.BooleanField(null=True, blank=True)
    # Standard output/logs from the script.
    output = models.TextField(blank=True)
    # Error details if the script failed.
    error_message = models.TextField(blank=True)

    # The unique ID of the Celery task running this visualization.
    # Used to monitor or cancel the background process.
    celery_task_id = models.CharField(max_length=255, blank=True)

    class Meta:
        """Default ordering: newest runs first."""
        ordering = ['-created_at']


class ResultsVisualizationPlot(models.Model):
    """
    Stores an image (plot) generated by a results visualization script.
    Plots are stored as files in the default storage (S3 or local).
    """

    # Link back to the run that generated this plot.
    visualization_run = models.ForeignKey(
        ResultsVisualizationRun,
        on_delete=models.CASCADE,
        related_name='plots'
    )

    # Human-readable title for the plot.
    title = models.CharField(max_length=255)

    # The order in which the plot was generated (e.g., 1, 2, 3, 4).
    plot_number = models.IntegerField()

    # The image file stored in S3/Filesystem
    image_data = models.ImageField(upload_to=results_visualization_plot_path, max_length=512)

    # SVG representation of the plot
    svg_data = models.FileField(upload_to=results_visualization_plot_path, max_length=512, blank=True, null=True)

    # Timestamp when the plot was saved.
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        """Order plots by their sequence number and ensure uniqueness per run."""
        ordering = ['plot_number']
        unique_together = ['visualization_run', 'plot_number']
